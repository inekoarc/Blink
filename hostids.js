/**
 * 主机 ID 分配器。
 *
 * 设计要点：
 *  - 池中每个名字全局唯一（构造时去重）。
 *  - assign() 从池中挑一个尚未被占用的名字分配给新主机；release(id) 在主机断开时归还。
 *  - 「回收策略：释放复用」。
 *    理由：本系统的主机是临时的 WebSocket 连接（无持久账号），若不回收，有限名字池会在
 *    少量连接后就枯竭，新主机只能拿到兜底名。采用「断开即释放、可复用」能在有限池内持续服务
 *    大量短暂连接。由于每条消息本身带有唯一 UUID 与时间戳，同一个角色名在不同时段被不同主机
 *    复用时，不会产生消息身份混淆——它只是「本场次」的展示人格，而非消息的唯一主键。
 */
class HostIdAllocator {
  constructor(pool) {
    this.pool = Array.from(new Set(pool || [])); // 去重，保证池内名字唯一
    this.used = new Set(); // 当前已被占用的名字
  }

  /** 从未被占用的名字中随机挑一个分配给新主机（避免单人测试时永远拿到池首的名字）；池耗尽时返回「旅人N」式兜底名（仍保证本轮唯一）。 */
  assign() {
    const free = this.pool.filter((n) => !this.used.has(n));
    if (free.length) {
      const name = free[Math.floor(Math.random() * free.length)];
      this.used.add(name);
      return name;
    }
    let i = 1;
    while (this.used.has(`旅人${i}`)) i++;
    const fallback = `旅人${i}`;
    this.used.add(fallback);
    return fallback;
  }

  /** 主机断开时释放其占用的 ID，供后续复用。 */
  release(id) {
    if (id) this.used.delete(id);
  }

  get assignedCount() {
    return this.used.size;
  }

  get total() {
    return this.pool.length;
  }
}

module.exports = { CHARACTER_POOL, HostIdAllocator };
